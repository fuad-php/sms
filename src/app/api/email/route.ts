import { NextRequest, NextResponse } from 'next/server'
import { getServerSession } from 'next-auth'
import { authOptions } from '@/lib/auth'
import { prisma } from '@/lib/prisma'
import { TicketExporter } from '@/lib/export'
import { z } from 'zod'
import nodemailer from 'nodemailer'

const emailSchema = z.object({
  ticketId: z.string(),
  recipientEmail: z.string().email(),
  subject: z.string().optional(),
  message: z.string().optional(),
  format: z.enum(['pdf', 'image']).default('pdf'),
  quality: z.enum(['low', 'medium', 'high']).default('high'),
  watermark: z.string().optional(),
  signature: z.string().optional(),
})

export async function POST(request: NextRequest) {
  try {
    const session = await getServerSession(authOptions)
    
    if (!session?.user?.id) {
      return NextResponse.json({ error: 'Unauthorized' }, { status: 401 })
    }

    const body = await request.json()
    const { 
      ticketId, 
      recipientEmail, 
      subject, 
      message, 
      format, 
      quality, 
      watermark, 
      signature 
    } = emailSchema.parse(body)

    // Get ticket from database
    const ticket = await prisma.ticket.findFirst({
      where: {
        id: ticketId,
        userId: session.user.id,
      },
    })

    if (!ticket) {
      return NextResponse.json({ error: 'Ticket not found' }, { status: 404 })
    }

    // Export ticket
    const exporter = TicketExporter.getInstance()
    let blob: Blob

    if (format === 'pdf') {
      blob = await exporter.exportToPDF(ticket.standardizedData as any, {
        format: 'pdf',
        quality,
        watermark,
        signature,
      })
    } else {
      blob = await exporter.exportToImage(ticket.standardizedData as any, {
        format: 'image',
        quality,
        watermark,
        signature,
      })
    }

    // Create email transporter
    const transporter = nodemailer.createTransporter({
      host: process.env.SMTP_HOST,
      port: parseInt(process.env.SMTP_PORT || '587'),
      secure: false,
      auth: {
        user: process.env.SMTP_USER,
        pass: process.env.SMTP_PASS,
      },
    })

    // Prepare email content
    const emailSubject = subject || `Your Standardized Ticket - ${ticket.originalFileName}`
    const emailMessage = message || `
      Hello,
      
      Please find attached your standardized ticket copy generated by Pro Ticketer.
      
      Original file: ${ticket.originalFileName}
      Generated on: ${new Date().toLocaleString()}
      
      Best regards,
      Pro Ticketer Team
    `

    // Convert blob to buffer
    const buffer = Buffer.from(await blob.arrayBuffer())
    const filename = `ticket_${ticket.originalFileName.split('.')[0]}_${Date.now()}.${format === 'pdf' ? 'pdf' : 'png'}`

    // Send email
    await transporter.sendMail({
      from: process.env.SMTP_USER,
      to: recipientEmail,
      subject: emailSubject,
      text: emailMessage,
      html: `
        <div style="font-family: Arial, sans-serif; max-width: 600px; margin: 0 auto;">
          <h2 style="color: #3b82f6;">Pro Ticketer</h2>
          <p>Hello,</p>
          <p>Please find attached your standardized ticket copy generated by Pro Ticketer.</p>
          <div style="background: #f9fafb; padding: 16px; border-radius: 8px; margin: 16px 0;">
            <p><strong>Original file:</strong> ${ticket.originalFileName}</p>
            <p><strong>Generated on:</strong> ${new Date().toLocaleString()}</p>
            <p><strong>Passenger:</strong> ${(ticket.standardizedData as any).passengerName || 'N/A'}</p>
            <p><strong>Flight:</strong> ${(ticket.standardizedData as any).flightNumber || 'N/A'}</p>
          </div>
          <p>Best regards,<br>Pro Ticketer Team</p>
        </div>
      `,
      attachments: [
        {
          filename: filename,
          content: buffer,
          contentType: format === 'pdf' ? 'application/pdf' : 'image/png',
        },
      ],
    })

    // Update ticket status
    await prisma.ticket.update({
      where: { id: ticketId },
      data: {
        status: 'EXPORTED',
        exportedAt: new Date(),
      },
    })

    return NextResponse.json({
      success: true,
      message: 'Ticket sent successfully',
      recipient: recipientEmail,
    })

  } catch (error) {
    if (error instanceof z.ZodError) {
      return NextResponse.json(
        { error: 'Validation error', details: error.errors },
        { status: 400 }
      )
    }

    console.error('Email error:', error)
    return NextResponse.json(
      { error: 'Internal server error' },
      { status: 500 }
    )
  }
}